"""
Generate tests/gpu/include/lwasv_fixture.h: LWA-SV geometry and the GCF texture used by
the standalone GPU tests and benchmarks, so they run on the worker nodes without Python/LSL.

Uses the same code as epic++: epic_geometry.array_frame / gen_loc_lwasv conventions and
the prolate-spheroidal texture of py_funcs.hpp:ProlateSpheroidalToTex2D.

usage: python make_fixture.py <path to src/python> <out header> [chan0] [grid_size] [grid_res_deg]
"""
import sys

import numpy as np
from scipy.special import pro_ang1_cv, pro_cv

sys.path.insert(0, sys.argv[1])
import epic_geometry as eg  # noqa: E402

out = sys.argv[2]
chan0 = int(sys.argv[3]) if len(sys.argv) > 3 else 2000
grid_size = int(sys.argv[4]) if len(sys.argv) > 4 else 128
grid_res = float(sys.argv[5]) if len(sys.argv) > 5 else 1.056
nstand = 256


def gen_loc(mode):
    """gen_loc_lwasv() in grid units of delta (before the per-channel wavenumber scaling)."""
    xyz = eg.stand_xyz()
    _, F, _ = eg.array_frame(mode)
    loc = xyz @ F.T
    loc[[i for i, a in enumerate(eg.lwasv.antennas[::2]) if a.stand.id == 256], :] = 0.0
    delta = (2 * grid_size * np.sin(np.pi * grid_res / 360)) ** -1
    loc = loc / delta
    loc -= np.min(loc, axis=0, keepdims=True)
    loc -= np.max(loc, axis=0, keepdims=True) / 2.0
    return loc, delta


def tex(dim, m=0, n=0, alpha=0.5, c=5.356 * np.pi / 2.0):
    """py_funcs.hpp:ProlateSpheroidalToTex2D"""
    cv = pro_cv(m, n, c)
    u = np.arange(dim) / dim
    f = np.power(1 - u * u, alpha) * pro_ang1_cv(m, n, c, cv, u)[0]
    t = np.outer(f, f)
    t[-1, :] = 0
    t[:, -1] = 0
    return t


def flit(v):
    t = f"{v:.9g}"
    if "." not in t and "e" not in t:
        t += ".0"
    return t + "f"


def arr(name, a, ctype="float"):
    a = np.asarray(a).ravel()
    body = ",\n  ".join(", ".join(flit(v) if ctype == "float" else str(int(v)) for v in a[i:i + 8])
                        for i in range(0, len(a), 8))
    return f"inline constexpr {ctype} {name}[{len(a)}] = {{\n  {body}\n}};\n"


used = eg.used_stands()
plane, delta = gen_loc("plane")
zen, _ = gen_loc("zenith")
_, _, w_plane = eg.array_frame("plane")
_, _, w_zen = eg.array_frame("zenith")
pc_az, pc_el = eg.phase_center_azel("plane")
lam0 = 299792458.0 / (chan0 * 25e3)
tex_dim = int(np.sqrt(0.1313 * lam0 ** 2) * 10)   # station_desc.hpp:GetAEff, MOFF_correlator.hpp
gcf = tex(tex_dim)

with open(out, "w") as fh:
    fh.write("// Generated by tests/gpu/tools/make_fixture.py - do not edit.\n")
    fh.write("#pragma once\n\nnamespace lwasv_fixture {\n")
    fh.write(f"inline constexpr int kNStands = {nstand};\n")
    fh.write(f"inline constexpr int kChan0 = {chan0};\n")
    fh.write(f"inline constexpr int kGridSize = {grid_size};\n")
    fh.write(f"inline constexpr double kGridRes = {grid_res!r};\n")
    fh.write(f"inline constexpr double kDelta = {delta!r};\n")
    fh.write(f"inline constexpr double kPlaneAz = {pc_az!r};\n")
    fh.write(f"inline constexpr double kPlaneEl = {pc_el!r};\n")
    fh.write(f"inline constexpr int kGcfTexDim = {tex_dim};\n")
    fh.write("// Stand positions from gen_loc_lwasv (x, y, z per stand) for each phase-centre mode\n")
    fh.write(arr("kLocPlane", plane.astype(np.float32)))
    fh.write(arr("kLocZenith", zen.astype(np.float32)))
    fh.write("// Residual w (m) after phasing to the phase centre\n")
    fh.write(arr("kWPlane", w_plane.astype(np.float32)))
    fh.write(arr("kWZenith", w_zen.astype(np.float32)))
    fh.write("// 1 if the stand is imaged (gen_phases_lwasv mask)\n")
    fh.write(arr("kUsed", used.astype(int), "int"))
    fh.write("// Prolate-spheroidal GCF texture, kGcfTexDim x kGcfTexDim, row-major\n")
    fh.write(arr("kGcfTex", gcf.astype(np.float32)))
    fh.write("}  // namespace lwasv_fixture\n")
print(f"wrote {out}: chan0={chan0} tex_dim={tex_dim} used={used.sum()} plane normal az={pc_az:.2f} el={pc_el:.3f}")
